"""Benchmark report: ``docs/eval_results.md`` and ``docs/eval_chart.png`` (R-EV-7).

Both are generated from the committed ``results/*.jsonl`` files only; nothing is typed by hand.
Rows follow ``data/bench_plan.json``: a planned run without a complete results file is shown as
"not run yet", never estimated. Runs with the ``fake`` provider are harness checks, not
accuracy, and are left out. Every row names the prompt version it used.

Chart colours: categorical slots 1-2 (blue, orange) of the dataviz reference palette, which is
documented as passing the all-pairs colour-vision checks for its first three slots.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from simagent.evaluation.summary import read_records, summarise
from simagent.evaluation.tasks import CATEGORIES

SERIES = {"baseline": "#2a78d6", "repair": "#eb6834"}
SURFACE = "#fcfcfb"
INK = "#0b0b0b"
INK_2 = "#52514e"
GRID = "#e4e3df"
HEADER = (
    "# Evaluation results\n\n"
    "Generated by `scripts/report.py` from `results/*.jsonl`, `data/bench_plan.json` and "
    "`data/prices.json`; do not edit by hand.\n"
)
NOT_RUN = "not run yet"
Key = tuple[str, str, int, str]


def run_key(provider: Any, model: Any, prompt_version: Any, mode: Any) -> Key:
    return (str(provider), str(model), int(prompt_version or 1), str(mode))


def load_runs(results_dir: Path) -> dict[Key, dict[str, Any]]:
    """Complete runs by key: ``{"summary": ..., "records": [...], "file": name}``."""
    runs: dict[Key, dict[str, Any]] = {}
    for path in sorted(results_dir.glob("*.jsonl")):
        records = read_records(path)
        if not records or records[0].get("provider") == "fake":
            continue
        s = summarise(records)
        key = run_key(s["provider"], s["model"], s["prompt_version"], s["mode"])
        runs[key] = {"summary": s, "records": records, "file": path.name}
    return runs


def load_json(path: Path, default: dict[str, Any]) -> dict[str, Any]:
    if not path.is_file():
        return default
    data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return data


def _fmt(value: Any, spec: str = "", suffix: str = "") -> str:
    if value is None:
        return "n/a"
    return f"{value:{spec}}{suffix}"


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{100 * value:.0f} %"


def token_cells(records: list[dict[str, Any]]) -> tuple[str, str]:
    """(total, per task) input/output tokens over the tasks whose provider reported them.

    Tasks without reported tokens (e.g. a call the server aborted) are excluded and counted, so
    the numbers stay exact instead of turning the whole run into n/a.
    """
    known = [
        r
        for r in records
        if r.get("input_tokens") is not None and r.get("output_tokens") is not None
    ]
    if not known:
        return "n/a / n/a", "n/a / n/a"
    tin = sum(int(r["input_tokens"]) for r in known)
    tout = sum(int(r["output_tokens"]) for r in known)
    k, n = len(known), len(records)
    note = "" if k == n else f" ({k} of {n} tasks reported)"
    return f"{tin:,} / {tout:,}{note}", f"{tin / k:,.0f} / {tout / k:,.0f}{note}"


def _cost(summary: dict[str, Any], prices: dict[str, Any]) -> str:
    if summary["cost_usd_total"] is not None:
        return f"{summary['cost_usd_total']:.4f} USD"
    entry = (prices.get("models") or {}).get(f"{summary['provider']}/{summary['model']}")
    if isinstance(entry, dict) and entry.get("note"):
        return str(entry["note"])
    if summary["provider"] == "ollama":
        return "n/a: local model"
    return "n/a: no official price recorded"


def _ordered(plan: dict[str, Any], runs: dict[Key, dict[str, Any]]) -> list[tuple[Any, Key]]:
    """(plan entry or None, key) in plan order, then complete runs that are not in the plan."""
    rows: list[tuple[Any, Key]] = []
    seen: set[Key] = set()
    for entry in plan.get("runs", []):
        key = run_key(entry["provider"], entry["model"], entry["prompt_version"], entry["mode"])
        rows.append((entry, key))
        seen.add(key)
    rows += [(None, key) for key in runs if key not in seen]
    return rows


def _run_cells(run: dict[str, Any], prices: dict[str, Any]) -> list[str]:
    s = run["summary"]
    n = s["tasks"]
    latency = (
        f"{_fmt(s['latency_median_s'], '.1f', ' s')} / {_fmt(s['latency_p90_s'], '.1f', ' s')}"
    )
    total, per_task = token_cells(run["records"])
    return [
        str(n),
        f"{_pct(s['success_rate'])} ({s['passed']}/{n})",
        _fmt(s["mean_attempts_solved"], ".2f"),
        str(s["repaired_successes"]),
        str(s["status_solved_but_wrong"]),
        str(s["policy_violations"]),
        str(s["timeouts"]),
        latency,
        _fmt(s["ttft_median_s"], ".2f", " s"),
        _fmt(s["tokens_per_s_median"], ".0f"),
        total,
        per_task,
        _cost(s, prices),
        _fmt(s["peak_vram_mib"], "", " MiB"),
    ]


def render_markdown(
    runs: dict[Key, dict[str, Any]], plan: dict[str, Any], prices: dict[str, Any]
) -> str:
    rows = _ordered(plan, runs)
    if not rows:
        return HEADER + "\nNo benchmark results have been committed yet.\n"
    out = [HEADER]
    if runs:
        out.append("![Success rate and latency](eval_chart.png)\n")
    out.append(
        "Prompt versions: **v1** = original system prompt; **v2** = v1 plus one general "
        "instruction to start every script with `import photonsim as ps` and "
        "`import simagent_io` (see `docs/NOTES.md`). Round 1 = v1 on `qwen2.5-coder:3b`; "
        "round 2 = v2 on every model.\n"
    )
    out.append("## Runs\n")
    out.append(
        "| round | provider | model | prompt | mode | tasks | success | mean attempts (solved) | "
        "repaired | solved but wrong | policy violations | timeouts | latency median / p90 | "
        "TTFT median | tokens/s median | tokens in / out (total) | tokens in / out (per task) | "
        "cost | peak VRAM |"
    )
    out.append("|" + "---|" * 19)
    notes: list[str] = []
    for entry, key in rows:
        provider, model, prompt, mode = key
        note = (entry or {}).get("note")
        marker = ""
        if note:
            if note not in notes:
                notes.append(note)
            marker = f" [{notes.index(note) + 1}]"
        head = [str(entry["round"]) if entry else "-", provider, f"`{model}`{marker}"]
        head += [f"v{prompt}", mode]
        run = runs.get(key)
        if run is None:
            out.append("| " + " | ".join([*head, "-", NOT_RUN] + ["-"] * 13) + " |")
        else:
            out.append("| " + " | ".join(head + _run_cells(run, prices)) + " |")
    if notes:
        out.append("")
        out += [f"[{i}] {note}." for i, note in enumerate(notes, start=1)]
    out.append(_versions_section(runs))
    out.append(_category_section(rows, runs))
    out.append(
        "\n`repaired`: tasks passed after more than one attempt. `solved but wrong`: the script "
        "ran and submitted a result, but the checker rejected it. Tokens, TTFT and tokens/s are "
        "`n/a` when the provider did not report them. Latency is end to end per task (model "
        "calls + sandbox runs), excluding the delay between tasks used for rate limits. "
        "Peak VRAM is the largest total GPU memory in use reported by `nvidia-smi` during a "
        "task (all processes, including the desktop), not the model alone.\n"
    )
    out.append(_token_tables(rows, runs))
    return "\n".join(out)


def _versions_section(runs: dict[Key, dict[str, Any]]) -> str:
    lines = ["\n## Prompt v1 vs v2\n"]
    models = sorted({(k[0], k[1]) for k in runs if k[2] == 1})
    if not models:
        return "\n".join([*lines, f"Round 1 (prompt v1) is {NOT_RUN}.\n"])
    lines.append(
        "| provider | model | mode | v1 success | v2 success | v1 mean attempts | "
        "v2 mean attempts |"
    )
    lines.append("|" + "---|" * 7)
    for provider, model in models:
        for mode in ("baseline", "repair"):
            success, attempts = [], []
            for version in (1, 2):
                run = runs.get((provider, model, version, mode))
                if run is None:
                    success.append(NOT_RUN)
                    attempts.append(NOT_RUN)
                    continue
                s = run["summary"]
                success.append(f"{_pct(s['success_rate'])} ({s['passed']}/{s['tasks']})")
                attempts.append(_fmt(s["mean_attempts_solved"], ".2f"))
            cells = [provider, f"`{model}`", mode, *success, *attempts]
            lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _category_section(rows: list[tuple[Any, Key]], runs: dict[Key, dict[str, Any]]) -> str:
    lines = ["\n## Success rate by category\n"]
    lines.append("| model | prompt | mode | " + " | ".join(CATEGORIES) + " |")
    lines.append("|" + "---|" * (len(CATEGORIES) + 3))
    for _, key in rows:
        run = runs.get(key)
        if run is None:
            continue
        s = run["summary"]
        cells = []
        for c in CATEGORIES:
            rate = s["success_rate_by_category"].get(c)
            n = s["tasks_by_category"].get(c, 0)
            cells.append(f"{_pct(rate)} of {n}" if rate is not None else "-")
        lines.append(f"| `{key[1]}` | v{key[2]} | {key[3]} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _token_tables(rows: list[tuple[Any, Key]], runs: dict[Key, dict[str, Any]]) -> str:
    lines = ["## Tokens per task\n"]
    lines.append(
        "Input and output tokens for every task, as reported by the provider, so cost can be "
        "computed later for any price.\n"
    )
    for _, key in rows:
        run = runs.get(key)
        if run is None:
            continue
        provider, model, prompt, mode = key
        lines.append(f"<details><summary>{provider} {model}, prompt v{prompt}, {mode}</summary>\n")
        lines.append(
            "| task | category | passed | attempts | input tokens | output tokens | latency |"
        )
        lines.append("|---|---|---|---|---|---|---|")
        for r in run["records"]:
            lines.append(
                f"| {r['task_id']} | {r['category']} | {'yes' if r['passed'] else 'no'} | "
                f"{r['attempts']} | {_fmt(r.get('input_tokens'), ',')} | "
                f"{_fmt(r.get('output_tokens'), ',')} | {r['latency_s']:.1f} s |"
            )
        lines.append("\n</details>\n")
    return "\n".join(lines)


README_START = "<!-- results:start (generated by scripts/report.py; do not edit) -->"
README_END = "<!-- results:end -->"


def render_readme_block(
    runs: dict[Key, dict[str, Any]], plan: dict[str, Any], prices: dict[str, Any]
) -> str:
    """Compact results table for the README, from the same data as the full report."""
    lines = [README_START, ""]
    pairs: dict[tuple[str, str, int], dict[str, Any]] = {}
    order: list[tuple[str, str, int]] = []
    for _, key in _ordered(plan, runs):
        group = (key[0], key[1], key[2])
        if group not in pairs:
            pairs[group] = {}
            order.append(group)
        pairs[group][key[3]] = runs.get(key)
    if not order:
        lines += ["No benchmark results have been committed yet.", "", README_END]
        return "\n".join(lines)
    lines.append(
        "| model | prompt | baseline (1 attempt) | repair (up to 4) | median latency, repair | "
        "tokens in / out per task, repair | cost |"
    )
    lines.append("|---|---|---|---|---|---|---|")
    for provider, model, prompt in order:
        modes = pairs[(provider, model, prompt)]
        cells = []
        for mode in ("baseline", "repair"):
            run = modes.get(mode)
            if run is None:
                cells.append(NOT_RUN)
            else:
                s = run["summary"]
                cells.append(f"{_pct(s['success_rate'])} ({s['passed']}/{s['tasks']})")
        rep = modes.get("repair")
        if rep is None:
            cells += [NOT_RUN, NOT_RUN, NOT_RUN]
        else:
            s = rep["summary"]
            cells.append(_fmt(s["latency_median_s"], ".1f", " s"))
            cells.append(token_cells(rep["records"])[1])
            cells.append(_cost(s, prices))
        lines.append(f"| {provider} `{model}` | v{prompt} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "36 tasks per run. Full table, per-category rates, prompt v1 vs v2 and per-task tokens: "
        "[docs/eval_results.md](docs/eval_results.md).",
        "",
        README_END,
    ]
    return "\n".join(lines)


def replace_block(text: str, block: str) -> str:
    """Swap the generated block in README text (markers included)."""
    start, end = text.find(README_START), text.find(README_END)
    if start < 0 or end < 0:
        raise ValueError("README is missing the results markers")
    return text[:start] + block + text[end + len(README_END) :]


def _label(key: Key) -> str:
    return f"{key[1]} (prompt v{key[2]})"


def render_chart(
    runs: dict[Key, dict[str, Any]], out: Path, order: list[Key] | None = None
) -> None:
    """Two panels: success rate by model and mode; median latency vs success rate."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    keys = [k for k in (order or list(runs)) if k in runs]
    groups = list(dict.fromkeys(_label(k) for k in keys))
    by_group = {(_label(k), k[3]): r["summary"] for k, r in runs.items()}
    fig, (ax1, ax2) = plt.subplots(
        1, 2, figsize=(11.5, 0.6 * len(groups) + 2.6), dpi=150, facecolor=SURFACE
    )
    for ax in (ax1, ax2):
        ax.set_facecolor(SURFACE)
        for side in ("top", "right"):
            ax.spines[side].set_visible(False)
        for side in ("left", "bottom"):
            ax.spines[side].set_color(GRID)
        ax.tick_params(colors=INK_2, labelsize=8)

    height = 0.3
    for j, mode in enumerate(("baseline", "repair")):
        first = True
        for i, group in enumerate(groups):
            s = by_group.get((group, mode))
            if s is None or s["success_rate"] is None:
                continue
            y = i + (j - 0.5) * (height + 0.04)
            value = 100 * s["success_rate"]
            ax1.barh(y, value, height=height, color=SERIES[mode], label=mode if first else None)
            first = False
            ax1.text(value + 1.5, y, f"{value:.0f}%", va="center", fontsize=7.5, color=INK)
    ax1.set_yticks(range(len(groups)), groups)
    ax1.invert_yaxis()
    ax1.set_xlim(0, 110)
    ax1.set_xlabel("tasks passed (%)", color=INK_2, fontsize=8)
    ax1.xaxis.grid(True, color=GRID, linewidth=0.8)
    ax1.set_axisbelow(True)
    ax1.set_title("Success rate by model, prompt and mode", color=INK, fontsize=10, loc="left")
    ax1.legend(frameon=False, fontsize=8, loc="lower right", labelcolor=INK)

    def _point(group: str, mode: str) -> tuple[float, float] | None:
        s = by_group.get((group, mode))
        if s is None or s["latency_median_s"] is None or s["success_rate"] is None:
            return None
        return float(s["latency_median_s"]), 100 * float(s["success_rate"])

    placed: list[tuple[float, float]] = []
    for group in groups:
        base, rep = _point(group, "baseline"), _point(group, "repair")
        if base is not None and rep is not None:
            ax2.plot([base[0], rep[0]], [base[1], rep[1]], color=GRID, linewidth=2, zorder=2)
        anchor = rep or base
        if anchor is not None:
            # Move a label below its point when another label sits close above/right of it.
            near = any(abs(anchor[1] - y) < 6 and abs(anchor[0] - x) < 6 for x, y in placed)
            placed.append(anchor)
            ax2.annotate(
                group,
                anchor,
                textcoords="offset points",
                xytext=(7, -11 if near else 3),
                fontsize=7,
                color=INK_2,
            )
    for mode in ("baseline", "repair"):
        pts = [p for g in groups if (p := _point(g, mode)) is not None]
        ax2.scatter(
            [p[0] for p in pts],
            [p[1] for p in pts],
            s=55,
            color=SERIES[mode],
            edgecolors=SURFACE,
            linewidths=2,
            label=mode,
            zorder=3,
        )
    ax2.set_xlabel("median end-to-end latency per task (s)", color=INK_2, fontsize=8)
    ax2.set_ylabel("tasks passed (%)", color=INK_2, fontsize=8)
    ax2.set_ylim(0, 105)
    xs = [p[0] for g in groups for md in SERIES if (p := _point(g, md)) is not None]
    ax2.set_xlim(0, 1.45 * max(xs) if xs else 1.0)  # room for labels on the right
    ax2.grid(True, color=GRID, linewidth=0.8)
    ax2.set_axisbelow(True)
    ax2.set_title("Latency vs success", color=INK, fontsize=10, loc="left")
    ax2.legend(frameon=False, fontsize=8, loc="lower right", labelcolor=INK)
    fig.tight_layout()
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, facecolor=SURFACE, metadata={"Software": None})
    plt.close(fig)


def build(root: Path, results_dir: Path | None = None) -> tuple[dict[Key, dict[str, Any]], str]:
    """Load everything the report needs and render the markdown."""
    runs, plan, prices = _inputs(root, results_dir)
    return runs, render_markdown(runs, plan, prices)


def _inputs(
    root: Path, results_dir: Path | None
) -> tuple[dict[Key, dict[str, Any]], dict[str, Any], dict[str, Any]]:
    runs = load_runs(results_dir or root / "results")
    plan = load_json(root / "data" / "bench_plan.json", {"runs": []})
    prices = load_json(root / "data" / "prices.json", {"models": {}})
    return runs, plan, prices


def readme_block(root: Path, results_dir: Path | None = None) -> str:
    runs, plan, prices = _inputs(root, results_dir)
    return render_readme_block(runs, plan, prices)


def write_report(root: Path, results_dir: Path | None = None, docs_dir: Path | None = None) -> int:
    """Write the markdown report and (when there are results) the chart; returns #runs."""
    runs, markdown = build(root, results_dir)
    docs = docs_dir or root / "docs"
    docs.mkdir(parents=True, exist_ok=True)
    (docs / "eval_results.md").write_text(markdown, encoding="utf-8", newline="\n")
    readme = root / "README.md"
    if readme.is_file() and README_START in readme.read_text(encoding="utf-8"):
        text = replace_block(readme.read_text(encoding="utf-8"), readme_block(root, results_dir))
        readme.write_text(text, encoding="utf-8", newline="\n")
    chart = docs / "eval_chart.png"
    if runs:
        plan = load_json(root / "data" / "bench_plan.json", {"runs": []})
        render_chart(runs, chart, [key for _, key in _ordered(plan, runs)])
    elif chart.exists():
        chart.unlink()
    return len(runs)
