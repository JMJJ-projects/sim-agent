"""Benchmark report: ``docs/eval_results.md`` and ``docs/eval_chart.png`` (R-EV-7).

Both are generated from the committed ``results/*.jsonl`` files only; nothing is typed by hand.
Runs with the ``fake`` provider are harness checks, not accuracy, and are left out.

Chart colours: categorical slots 1-2 (blue, orange) of the dataviz reference palette, which is
documented as passing the all-pairs colour-vision checks for its first three slots.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from simagent.evaluation.summary import read_records, summarise
from simagent.evaluation.tasks import CATEGORIES

SERIES = {"baseline": "#2a78d6", "repair": "#eb6834"}
SURFACE = "#fcfcfb"
INK = "#0b0b0b"
INK_2 = "#52514e"
GRID = "#e4e3df"
HEADER = (
    "# Evaluation results\n\n"
    "Generated by `scripts/report.py` from `results/*.jsonl`; do not edit by hand.\n"
)


def load_summaries(results_dir: Path) -> list[dict[str, Any]]:
    """One summary per results file, fake-provider runs excluded, sorted by model then mode."""
    out = []
    for path in sorted(results_dir.glob("*.jsonl")):
        records = read_records(path)
        if not records or records[0].get("provider") == "fake":
            continue
        summary = summarise(records)
        summary["run"] = path.stem
        out.append(summary)
    order = {"baseline": 0, "repair": 1}
    return sorted(out, key=lambda s: (str(s["provider"]), str(s["model"]), order[s["mode"]]))


def _fmt(value: Any, spec: str = "", suffix: str = "") -> str:
    if value is None:
        return "n/a"
    return f"{value:{spec}}{suffix}"


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{100 * value:.0f} %"


def render_markdown(summaries: list[dict[str, Any]]) -> str:
    if not summaries:
        return HEADER + "\nNo benchmark results have been committed yet.\n"
    lines = [HEADER, "![Success rate and latency](eval_chart.png)\n", "## Overview\n"]
    lines.append(
        "| provider | model | mode | tasks | success | mean attempts (solved) | repaired | "
        "solved but wrong | policy violations | timeouts | latency median / p90 | "
        "TTFT median | tokens/s median | tokens in / out | cost | peak VRAM |"
    )
    lines.append("|" + "---|" * 16)
    for s in summaries:
        cells = [
            str(s["provider"]),
            f"`{s['model']}`",
            str(s["mode"]),
            str(s["tasks"]),
            f"{_pct(s['success_rate'])} ({s['passed']})",
            _fmt(s["mean_attempts_solved"], ".2f"),
            str(s["repaired_successes"]),
            str(s["status_solved_but_wrong"]),
            str(s["policy_violations"]),
            str(s["timeouts"]),
            f"{_fmt(s['latency_median_s'], '.1f', ' s')} / {_fmt(s['latency_p90_s'], '.1f', ' s')}",
            _fmt(s["ttft_median_s"], ".2f", " s"),
            _fmt(s["tokens_per_s_median"], ".0f"),
            f"{_fmt(s['input_tokens_total'], ',')} / {_fmt(s['output_tokens_total'], ',')}",
            _fmt(s["cost_usd_total"], ".4f", " USD"),
            _fmt(s["peak_vram_mib"], "", " MiB"),
        ]
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("\n## Success rate by category\n")
    cats = [c for c in CATEGORIES if any(c in s["success_rate_by_category"] for s in summaries)]
    lines.append("| model | mode | " + " | ".join(cats) + " |")
    lines.append("|" + "---|" * (len(cats) + 2))
    for s in summaries:
        cells = []
        for c in cats:
            rate = s["success_rate_by_category"].get(c)
            n = s["tasks_by_category"].get(c, 0)
            cells.append(f"{_pct(rate)} of {n}" if rate is not None else "n/a")
        lines.append(f"| `{s['model']}` | {s['mode']} | " + " | ".join(cells) + " |")
    lines.append(
        "\n`repaired`: tasks passed after more than one attempt. `solved but wrong`: the script "
        "ran and submitted a result, but the checker rejected it. Token totals, TTFT and "
        "tokens/s are `n/a` when the provider did not report them; cost is `n/a` for local "
        "models and for hosted models without a dated entry in `data/prices.json`.\n"
    )
    return "\n".join(lines)


def _label(s: dict[str, Any]) -> str:
    return f"{s['provider']}/{s['model']}"


def render_chart(summaries: list[dict[str, Any]], out: Path) -> None:
    """Two panels: success rate by model and mode; median latency vs success rate."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    models = list(dict.fromkeys(_label(s) for s in summaries))
    fig, (ax1, ax2) = plt.subplots(
        1, 2, figsize=(11, 0.55 * len(models) + 2.6), dpi=150, facecolor=SURFACE
    )
    for ax in (ax1, ax2):
        ax.set_facecolor(SURFACE)
        for side in ("top", "right"):
            ax.spines[side].set_visible(False)
        for side in ("left", "bottom"):
            ax.spines[side].set_color(GRID)
        ax.tick_params(colors=INK_2, labelsize=8)

    height = 0.3
    for j, mode in enumerate(("baseline", "repair")):
        for i, model in enumerate(models):
            s = next((x for x in summaries if _label(x) == model and x["mode"] == mode), None)
            if s is None or s["success_rate"] is None:
                continue
            y = i + (j - 0.5) * (height + 0.04)
            ax1.barh(
                y,
                100 * s["success_rate"],
                height=height,
                color=SERIES[mode],
                label=mode if i == 0 else None,
            )
            ax1.text(
                100 * s["success_rate"] + 1.5,
                y,
                f"{100 * s['success_rate']:.0f}%",
                va="center",
                fontsize=7.5,
                color=INK,
            )
    ax1.set_yticks(range(len(models)), models)
    ax1.invert_yaxis()
    ax1.set_xlim(0, 110)
    ax1.set_xlabel("tasks passed (%)", color=INK_2, fontsize=8)
    ax1.xaxis.grid(True, color=GRID, linewidth=0.8)
    ax1.set_axisbelow(True)
    ax1.set_title("Success rate by model and mode", color=INK, fontsize=10, loc="left")
    ax1.legend(frameon=False, fontsize=8, loc="lower right", labelcolor=INK)

    def _point(model: str, mode: str) -> tuple[float, float] | None:
        s = next((x for x in summaries if _label(x) == model and x["mode"] == mode), None)
        if s is None or s["latency_median_s"] is None or s["success_rate"] is None:
            return None
        return float(s["latency_median_s"]), 100 * float(s["success_rate"])

    # A thin connector from each model's baseline point to its repair point, labelled once.
    for model in models:
        base, rep = _point(model, "baseline"), _point(model, "repair")
        if base is not None and rep is not None:
            ax2.plot([base[0], rep[0]], [base[1], rep[1]], color=GRID, linewidth=2, zorder=2)
        anchor = rep or base
        if anchor is not None:
            ax2.annotate(
                model.split("/", 1)[-1],
                anchor,
                textcoords="offset points",
                xytext=(7, 3),
                fontsize=7,
                color=INK_2,
            )
    for mode in ("baseline", "repair"):
        pts = [p for m in models if (p := _point(m, mode)) is not None]
        ax2.scatter(
            [p[0] for p in pts],
            [p[1] for p in pts],
            s=55,
            color=SERIES[mode],
            edgecolors=SURFACE,
            linewidths=2,
            label=mode,
            zorder=3,
        )
    ax2.set_xlabel("median end-to-end latency per task (s)", color=INK_2, fontsize=8)
    ax2.set_ylabel("tasks passed (%)", color=INK_2, fontsize=8)
    ax2.set_ylim(0, 105)
    xs = [p[0] for m in models for md in SERIES if (p := _point(m, md)) is not None]
    ax2.set_xlim(0, 1.3 * max(xs) if xs else 1.0)  # room for labels on the right
    ax2.grid(True, color=GRID, linewidth=0.8)
    ax2.set_axisbelow(True)
    ax2.set_title("Latency vs success", color=INK, fontsize=10, loc="left")
    ax2.legend(frameon=False, fontsize=8, loc="lower right", labelcolor=INK)
    fig.tight_layout()
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, facecolor=SURFACE, metadata={"Software": None})
    plt.close(fig)


def write_report(results_dir: Path, docs_dir: Path) -> list[dict[str, Any]]:
    """Write the markdown report and (when there are results) the chart."""
    summaries = load_summaries(results_dir)
    docs_dir.mkdir(parents=True, exist_ok=True)
    md = docs_dir / "eval_results.md"
    md.write_text(render_markdown(summaries), encoding="utf-8", newline="\n")
    chart = docs_dir / "eval_chart.png"
    if summaries:
        render_chart(summaries, chart)
    elif chart.exists():
        chart.unlink()
    return summaries
